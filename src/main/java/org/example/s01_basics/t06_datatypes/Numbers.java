package org.example.s01_basics.t06_datatypes;

/**
 * W3Schools - Java Data Types: Numbers
 * https://www.w3schools.com/java/java_data_types_numbers.asp
 */

public class Numbers {
    public static void main (String[] args){
        byte myNum = 100;
        System.out.println(myNum);

        short myShortNum = 5000;
        System.out.println(myShortNum);

        int myIntNum = 100000;
        System.out.println(myIntNum);

        long myLongNum = 15000000000L;
        System.out.println(myLongNum);

        float myFloatNum = 5.75f;
        System.out.println(myFloatNum);

        double myDoubleNum = 19.99d;
        System.out.println(myDoubleNum);

        float f1 = 35e3f;
        double d1 = 12e5d;
        System.out.println(f1);
        System.out.println(d1);


    }

}
