package org.example.s01_basics.t09_strings;

/**
 * W3Schools - Java Strings: Special Characters
 * https://www.w3schools.com/java/java_strings_specchars.asp
 */
public class SpecialCharacters {
    public static void main (String[] args){
        String txt = "We are the so-called \"Vikings\" from the north";
        System.out.println(txt);
        System.out.println("It\'s alright");
        System.out.println("The character \\ is called backslash.");
        System.out.println("Test\nTest 2");
        System.out.println("Test\tTest 2");
        System.out.println("Test\bTest 2");
    }
}